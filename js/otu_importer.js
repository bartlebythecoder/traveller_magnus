    /**
     * Wipes the map and resizes the canvas for a new-document bulk import.
     * Shared by the Universe and Neighbourhood imports so the two cannot drift
     * apart (mirrors clearCanvas in io_manager.js, minus the confirm prompt).
     */
    async function resetCanvasForBulkImport(width, height) {
        // Leave the System Viewer stack if open — its system belongs to a hex
        // that is about to be wiped. Innermost first, as in clearCanvas.
        if (typeof ApproachViewer !== 'undefined' && ApproachViewer.isOpen()) ApproachViewer.close();
        if (typeof SurfaceViewer  !== 'undefined' && SurfaceViewer.isOpen())  SurfaceViewer.close();
        if (typeof SystemViewer   !== 'undefined' && SystemViewer.isOpen())   SystemViewer.close();

        // Wipe IndexedDB before clearing memory so no stale data remains.
        // The sector download cache is kept — this import is about to read from it.
        if (window.dbManager) await window.dbManager.clearDB({ keepTsvCache: true });

        gridWidth  = width;
        gridHeight = height;
        hexStates.clear();
        window.sectorNames        = {};
        window.subsectorNames     = {};
        window.sectorRoutes       = [];
        window.routeDefinitions   = (typeof getDefaultRouteDefinitions === 'function') ? getDefaultRouteDefinitions() : [];
        window.undoStack          = [];
        window.redoStack          = [];
        selectedHexes.clear();
        window.hexBorderAssignments = new Map();
        window.borderPaths          = new Map();
        window.regionPaths          = new Map();
        window.borderDefinitions    = (typeof getDefaultBorderDefinitions === 'function') ? getDefaultBorderDefinitions() : [];
        window.regionDefinitions    = (typeof getDefaultRegionDefinitions === 'function') ? getDefaultRegionDefinitions() : [];

        centerCameraOnGrid();
        requestAnimationFrame(draw);

        // Persist the new grid dimensions immediately.
        if (window.dbManager) window.dbManager.saveGridDimensions();
    }

    /**
     * Clears only the given sector slots ahead of an in-place bulk import,
     * leaving the canvas size and every other sector untouched. Used by the
     * Neighbourhood import when its 3×3 block fits inside the current canvas.
     *
     * @param {number[]} slotNums - Every slot in the block, including slots
     *                              whose neighbour is missing (they end blank).
     * @param {object}   opts     - The import options (see executeBulkImport).
     */
    function clearBlockForBulkImport(slotNums, opts) {
        // Leave the System Viewer stack if open — its hex may be about to be
        // wiped. Innermost first, as in clearCanvas.
        if (typeof ApproachViewer !== 'undefined' && ApproachViewer.isOpen()) ApproachViewer.close();
        if (typeof SurfaceViewer  !== 'undefined' && SurfaceViewer.isOpen())  SurfaceViewer.close();
        if (typeof SystemViewer   !== 'undefined' && SystemViewer.isOpen())   SystemViewer.close();

        // Not undoable, for the same reason as runImport() — see the comment there.
        window.undoStack = [];
        window.redoStack = [];
        selectedHexes.clear();

        const inBlock = (hexId) => slotNums.includes(parseInt(String(hexId).split('-')[0], 10));

        if (opts.importSector) {
            slotNums.forEach(clearSectorSlotData);
            // Routes touching a cleared sector have lost their world, so they go too.
            if (window.sectorRoutes) {
                window.sectorRoutes = window.sectorRoutes.filter(r => !inBlock(r.startId) && !inBlock(r.endId));
            }
        } else if (opts.importRoutes && window.sectorRoutes) {
            // Replace only the block's Xboat routes (Route 1, as in runImport).
            window.sectorRoutes = window.sectorRoutes.filter(r =>
                r.routeId !== 1 || (!inBlock(r.startId) && !inBlock(r.endId)));
        }

        // Region outlines are keyed "<slot>:<label>"; drop the block's so a
        // re-import does not leave the previous sector's outlines behind.
        if (opts.importRegions && window.regionPaths) {
            for (const key of [...window.regionPaths.keys()]) {
                if (slotNums.includes(parseInt(key.split(':')[0], 10))) window.regionPaths.delete(key);
            }
        }
    }

    /**
     * Bulk-imports a list of sectors.
     *
     * By default the canvas is resized to width × height and all existing data
     * is cleared first. With opts.blockSlots set, the canvas is left as it is
     * and only those slots are cleared (width/height are then ignored).
     *
     * @param {Array}  sectors - [{ name, x, y, slot }] — x,y are travellermap
     *                           galaxy coords, slot is the canvas slot string.
     * @param {number} width   - Canvas width in sectors.
     * @param {number} height  - Canvas height in sectors.
     * @param {object} opts    - { importSector, importRoutes, importBorders,
     *                             importRegions, mixonForeven, importSystemData,
     *                             blockSlots }
     * @param {string} label   - "Universe" / "Neighbourhood", used in messages.
     */
    async function executeBulkImport(sectors, width, height, opts, label) {
        const needsMeta = needsMetadata(opts);

        if (opts.blockSlots) {
            clearBlockForBulkImport(opts.blockSlots, opts);
        } else {
            await resetCanvasForBulkImport(width, height);
        }

        const delay = (ms) => new Promise(resolve => setTimeout(resolve, ms));
        let errorCount = 0;

        // Build coord lookup from only the sectors being imported, so routes
        // leading out of the imported block are skipped rather than resolved
        // to the wrong slot.
        const coordLookup = new Map();
        sectors.forEach(s => coordLookup.set(`${s.x},${s.y}`, parseInt(s.slot, 10)));

        const universeMetas = [];
        const metaFailures = [];
        for (let i = 0; i < sectors.length; i++) {
            const { name, slot: defaultSlot, x, y } = sectors[i];
            let tsvFromCache = false;

            const isMixonForeven = opts.mixonForeven && name === 'Foreven';

            if (opts.importSector) {
                try {
                    if (isMixonForeven) {
                        // Use the embedded JS constant — no fetch needed (avoids CORS on file://).
                        if (!window.FOREVEN_MIXON_TSV) throw new Error('FOREVEN_MIXON_TSV not loaded. Run convert_foreven_mixon.ps1.');
                        tsvFromCache = true; // treat as always-available, no API delay needed

                        if (typeof showToast === 'function') {
                            showToast(`Importing Foreven (Mixon) into Slot ${defaultSlot}… [embedded]`);
                        }

                        const text = window.FOREVEN_MIXON_TSV;

                        if (typeof importT5Tab === 'function') {
                            importT5Tab(text, 'Foreven', defaultSlot, true);
                        } else {
                            throw new Error('importT5Tab not available');
                        }

                        const slotNum = parseInt(defaultSlot, 10);
                        if (!isNaN(slotNum)) {
                            window.sectorNames[slotNum] = 'Foreven';
                        }
                    } else {
                        const cached = await getCachedUniverseSector(name);
                        tsvFromCache = cached !== null;

                        if (typeof showToast === 'function') {
                            const source = tsvFromCache ? 'cache' : `API (${i + 1} of ${sectors.length})`;
                            showToast(`Importing ${name} into Slot ${defaultSlot}… [${source}]`);
                        }

                        const text = tsvFromCache ? cached : await fetchAndCacheUniverseSector(name);

                        // bulkMode=true: skip the per-sector rule re-application,
                        // allegiance scan, draw and DB write — those are done once after
                        // the loop. NOT saveHistoryState: this comment used to promise a
                        // deferred snapshot "done once after the loop" that was never
                        // written, and the post-loop block does no history save. A bulk
                        // import is deliberately not undoable — see where the undo stacks
                        // are cleared, above.
                        if (typeof importT5Tab === 'function') {
                            importT5Tab(text, name, defaultSlot, true);
                        } else {
                            throw new Error('importT5Tab not available');
                        }

                        const slotNum = parseInt(defaultSlot, 10);
                        if (!isNaN(slotNum)) {
                            window.sectorNames[slotNum] = name;
                        }
                    }
                } catch (err) {
                    console.warn(`[${label} Import] Failed to import "${name}": ${err.message}`);
                    errorCount++;
                }

                // Pause before metadata fetch only for live API calls (not local or cached).
                if (!tsvFromCache && !isMixonForeven) await delay(1000);
            }

            if (needsMeta) {
                if (isMixonForeven) {
                    // Use the locally embedded XML instead of travellermap metadata.
                    if (window.FOREVEN_MIXON_XML) {
                        universeMetas.push({ name: 'Foreven', metaXml: window.FOREVEN_MIXON_XML, slotNum: parseInt(defaultSlot, 10), x, y });
                    }
                } else {
                // Fetch and cache metadata, but defer parsing until all sectors are loaded.
                let metaXml = await getCachedUniverseMetadata(name);
                if (!metaXml) {
                    if (typeof showToast === 'function') showToast(`Fetching metadata for ${name}…`);
                    metaXml = await fetchAndCacheUniverseMetadata(name, x, y);
                    if (i < sectors.length - 1) await delay(1000);
                }
                if (metaXml) {
                    universeMetas.push({ name, metaXml, slotNum: parseInt(defaultSlot, 10), x, y });
                } else if (needsMeta) {
                    metaFailures.push(name);
                }
                } // end else (not isMixonForeven)
            }
        }

        // Post-processing deferred from bulkMode importT5Tab calls — run once here.
        if (opts.importSector) {
            if (typeof window.reapplyAllRules === 'function') window.reapplyAllRules();
            if (typeof window.applyActiveFilters === 'function') window.applyActiveFilters();
            if (window.dbManager) window.dbManager.syncAllHexes();
            if (window.dbManager) window.dbManager.saveSectorNames();
        }

        if (needsMeta && typeof parseAndAddOtuRoutes === 'function') {
            // Parse all routes/borders in a single pass after every sector is loaded,
            // so cross-sector routes can resolve both endpoints correctly.
            // Yield to the browser between sectors to keep the tab responsive.
            if (typeof showToast === 'function') showToast(`Processing metadata for ${universeMetas.length} sectors…`);
            for (const m of universeMetas) {
                parseAndAddOtuRoutes(m.name, m.metaXml, m.slotNum, m.x, m.y, coordLookup, opts);
                await delay(0);
            }
            if (typeof window.sortAndTrimBorderDefinitions === 'function') window.sortAndTrimBorderDefinitions();
            if (typeof window.renderBorderWindow === 'function') window.renderBorderWindow();
        }

        if (typeof window.renderBorderWindow === 'function') window.renderBorderWindow();
        if (typeof window.renderRegionWindow === 'function') window.renderRegionWindow();

        // Clearing a slot and the metadata pass can both change subsector names.
        if (window.dbManager) window.dbManager.saveSubsectorNames();

        if (opts.importSystemData && typeof applyOtuSystemData === 'function') {
            applyOtuSystemData();
        }

        // An in-place import kept the rest of the map in the DB, so persist the
        // routes, borders and regions it changed alongside it.
        if (opts.blockSlots && window.dbManager) window.dbManager.scheduleSyncAll();

        requestAnimationFrame(draw);

        let summary = errorCount > 0
            ? `${label} import complete. ${errorCount} sector(s) failed — see console for details.`
            : `${label} import complete! ${sectors.length} sector(s) loaded.`;
        if (metaFailures.length > 0) {
            const preview = metaFailures.slice(0, 3).join(', ') + (metaFailures.length > 3 ? `… (+${metaFailures.length - 3} more)` : '');
            summary += ` ${metaFailures.length} metadata fetch(es) failed (no borders/routes): ${preview}`;
            console.warn(`[${label} Import] Metadata fetch failed for: ${metaFailures.join(', ')}`);
        }
        if (typeof showToast === 'function') showToast(summary, 6000);
    }

