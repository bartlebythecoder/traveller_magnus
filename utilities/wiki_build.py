"""
utilities/wiki_build.py

Build step for the Traveller wiki snapshot (v0.19.0, manifest §0.0.D):

    python utilities/wiki_parse.py     # raw/ + corrections/ -> clean/ (+ parse_report.md)
    python utilities/wiki_build.py     # clean/ -> js/otu_system_data.js

Writes js/otu_system_data.js, which hex_map.html loads with every page (Sean, 2026-11-16).
It holds what the in-app loader needs and nothing else: the merged systems, with every field
that exists only for tracing back to the wiki stripped out (raw text, flags, sources, each
page's own infobox, star templates). Each system is one line, so a refresh shows in a diff as
the lines of the systems that changed.

Never contacts the wiki. Output is CRLF (the repo is CRLF).
"""

import json
import os
import sys
from collections import OrderedDict

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))
CLEAN_DIR = os.path.join(ROOT, "otu_systems", "clean")
OUT = os.path.join(ROOT, "js", "otu_system_data.js")

BUILD_VERSION = 1

# Fields that exist only to trace a value back to the wiki or to the review.
DROP_KEYS = {"raw", "name_raw", "flags", "sources", "stars_as_written", "unused_fields",
             "uwp_malformed", "uwp_source", "distance_source", "belt_source", "corrected", "why"}

# Top-level system fields the app needs, in this order.
SYSTEM_KEYS = ["sector", "sector_abbreviation", "hex", "subsector", "name", "single_hex_only"]


def strip(x):
    if isinstance(x, dict):
        out = OrderedDict()
        for k, v in x.items():
            if k in DROP_KEYS:
                continue
            if k == "distance" and isinstance(v, dict):
                v = OrderedDict((dk, dv) for dk, dv in v.items() if dk != "raw")
            out[k] = strip(v)
        return out
    if isinstance(x, list):
        return [strip(i) for i in x]
    return x


def main():
    files = sorted(f for f in os.listdir(CLEAN_DIR) if f.endswith(".json"))
    if not files:
        print("No clean files - run utilities/wiki_parse.py first.")
        return 1
    systems, snapshot, parser_versions = [], set(), set()
    for fn in files:
        with open(os.path.join(CLEAN_DIR, fn), encoding="utf-8") as f:
            s = json.load(f, object_pairs_hook=OrderedDict)
        snapshot.add(s.get("snapshot"))
        parser_versions.add(s.get("parser_version"))
        out = OrderedDict()
        for k in SYSTEM_KEYS:
            if s.get(k) is not None:
                out[k] = s[k]
        # Bulk loading matches on TravellerMap's name for the hex, not the wiki's spelling.
        tm = s.get("travellermap") or {}
        out["travellermap_name"] = tm.get("Name")
        out["travellermap_uwp"] = tm.get("UWP")
        out["systems"] = strip(s["systems"])
        systems.append(out)

    if len(snapshot) != 1 or len(parser_versions) != 1:
        print(f"Mixed clean files (snapshots {sorted(map(str, snapshot))}, parser versions "
              f"{sorted(map(str, parser_versions))}) - rerun utilities/wiki_parse.py.")
        return 1
    snap = snapshot.pop()
    pv = parser_versions.pop()

    lines = []
    lines.append("/**")
    lines.append(" * js/otu_system_data.js")
    lines.append(" *")
    lines.append(" * GENERATED by utilities/wiki_build.py - do not edit by hand. Fix the data in")
    lines.append(" * otu_systems/corrections/, then run utilities/wiki_parse.py and utilities/wiki_build.py.")
    lines.append(" *")
    lines.append(" * Published system data from the Traveller wiki (wiki.travellerrpg.com), cleaned offline")
    lines.append(f" * into a dated snapshot. Snapshot {snap}; parser v{pv}; build v{BUILD_VERSION}; "
                 f"{len(systems)} systems.")
    lines.append(" * See directives/project_manifest.md section 0.0.D for every ruling behind it.")
    lines.append(" */")
    lines.append("")
    lines.append("window.OTU_SNAPSHOT = {")
    lines.append(f"    snapshot: {json.dumps(snap)},")
    lines.append(f"    parserVersion: {pv},")
    lines.append(f"    buildVersion: {BUILD_VERSION},")
    lines.append("    systems: [")
    for i, s in enumerate(systems):
        sep = "," if i < len(systems) - 1 else ""
        lines.append("        " + json.dumps(s, ensure_ascii=False, separators=(",", ":")) + sep)
    lines.append("    ]")
    lines.append("};")
    text = "\n".join(lines) + "\n"
    with open(OUT, "wb") as f:
        f.write(text.replace("\n", "\r\n").encode("utf-8"))
    print(f"{len(systems)} systems -> {OUT} ({os.path.getsize(OUT):,} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
